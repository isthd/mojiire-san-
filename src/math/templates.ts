/** カタカナをひらがなにそろえ、大文字小文字・全角半角の差を吸収 */
function fold(s: string): string {
  return s
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
}

/** ラベル・グループ名・よみで検索（空白区切りの全語を含むもの） */
export function searchTemplates(query: string): TemplateItem[] {
  const words = fold(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const results: TemplateItem[] = [];
  const seen = new Set<string>();
  for (const g of TEMPLATE_GROUPS) {
    for (const it of g.items) {
      const hay = fold(`${it.label} ${g.label} ${it.keywords ?? ''}`);
      if (words.every((w) => hay.includes(w)) && !seen.has(it.latex)) {
        seen.add(it.latex);
        results.push(it);
      }
    }
  }
  return results;
}

/** プレビュー表示用：空欄を □ にした LaTeX */
export function toPreviewLatex(snippet: string): string {
  // \text{} の中では \square が使えないので文字の □ にする
  return snippet.replace(/\\text\{#[0?]\}/g, '\\text{□}').replace(/#0|#\?/g, '\\square ');
}

// 最近使ったテンプレート（端末ごと）
const RECENT_KEY = 'mojiire.mathTemplates.recent';
const RECENT_MAX = 16;

export function loadRecentTemplates(): TemplateItem[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    const list = raw ? (JSON.parse(raw) as unknown) : [];
    if (!Array.isArray(list)) return [];
    return list
      .filter((x): x is TemplateItem => !!x && typeof x.label === 'string' && typeof x.latex === 'string')
      .slice(0, RECENT_MAX);
  } catch {
    return [];
  }
}

export function pushRecentTemplate(item: TemplateItem): TemplateItem[] {
  const next = [item, ...loadRecentTemplates().filter((x) => x.latex !== item.latex)].slice(0, RECENT_MAX);
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next.map(({ label, latex }) => ({ label, latex }))));
  } catch {
    // 保存できない環境（プライベートモード等）では記録しない
  }
  return next;
}
