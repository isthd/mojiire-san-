// 数式テンプレート集。LaTeX を知らなくても、選んで □ を埋めるだけで答案・解説の数式が書けるようにする。
// #? = 空欄（□。タップして入力）。MathLive（入力欄）と MathJax（描画）の両方で解釈できる記法だけを使う。
import type { PaletteItem } from './palette';

export interface TemplateItem extends PaletteItem {
  /** 検索用のよみ・別名（スペース区切り） */
  keywords?: string;
}

export interface TemplateGroup {
  key: string;
  label: string;
  items: TemplateItem[];
}

// MathLive は「#?x」のように空欄の直後に文字が続くと空欄として認識しないため、間に空白を入れる
const t = (label: string, latex: string, keywords?: string): TemplateItem => ({
  label,
  latex: latex.replace(/#\?(?=[A-Za-z])/g, '#? '),
  keywords,
});

/** 単位：数値の空欄＋単位（立体の単位記号） */
const unit = (u: string, label: string, keywords?: string) => t(label, `#?\\,\\mathrm{${u}}`, `たんい 単位 ${keywords ?? ''}`);

